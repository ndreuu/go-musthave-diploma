// PostgresRepository is a PostgreSQL-backed implementation of the Storage interface.
//
// It provides persistent storage for users, orders, and withdrawals using
// PostgreSQL database tables. All methods use parameterized queries to prevent
// SQL injection attacks.
//
// The repository expects the database schema to be set up by running migrations
// via RunMigrations before use.
type PostgresRepository struct {
	// db is the underlying SQL database connection.
	db *sql.DB
}

// NewPostgresRepository creates a new PostgreSQL repository instance.
//
// Parameters:
//   - db: Active PostgreSQL database connection (should be created via sql.Open)
//
// Returns:
//   - *PostgresRepository: New repository instance ready for use
//
// Example usage:
//
//	db, err := sql.Open("postgres", dsn)
//	if err != nil {
//	    return nil, err
//	}
//	repo := repository.NewPostgresRepository(db)
func NewPostgresRepository(db *sql.DB) *PostgresRepository {
	return &PostgresRepository{db: db}
}

// CreateUser creates a new user with the given login and password hash.
//
// The user ID is auto-generated by the database. If a user with the same
// login already exists, returns ErrAlreadyExists.
//
// Parameters:
//   - ctx: Context for query cancellation and timeouts
//   - login: Unique username for the new user
//   - passwordHash: Bcrypt hash of the user's password
//
// Returns:
//   - *model.User: Pointer to the created user with assigned ID
//   - error: ErrAlreadyExists if login is taken, or database error
func (r *PostgresRepository) CreateUser(ctx context.Context, login string, passwordHash string) (*model.User, error) {
	const query = `
		INSERT INTO users (login, password_hash)
		VALUES ($1, $2)
		RETURNING id, login, password_hash
	`

	var user model.User
	err := r.db.QueryRowContext(ctx, query, login, passwordHash).
		Scan(&user.ID, &user.Login, &user.PasswordHash)
	if err != nil {
		var pgErr *pgconn.PgError
		if errors.As(err, &pgErr) && pgErr.Code == "23505" {
			return nil, ErrAlreadyExists
		}

		return nil, err
	}

	return &user, nil
}

// GetUserByLogin retrieves a user by their login username.
//
// Parameters:
//   - ctx: Context for query cancellation and timeouts
//   - login: Username to look up
//
// Returns:
//   - *model.User: Pointer to the user if found
//   - error: ErrNotFound if user doesn't exist, or database error
func (r *PostgresRepository) GetUserByLogin(ctx context.Context, login string) (*model.User, error) {
	const query = `
		SELECT id, login, password_hash
		FROM users
		WHERE login = $1
	`

	var user model.User
	err := r.db.QueryRowContext(ctx, query, login).
		Scan(&user.ID, &user.Login, &user.PasswordHash)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, ErrNotFound
		}

		return nil, err
	}

	return &user, nil
}

// CreateOrder creates a new order for the specified user.
//
// The order is created with status NEW and the current timestamp.
// If an order with the same number already exists, returns ErrAlreadyExists.
//
// Parameters:
//   - ctx: Context for query cancellation and timeouts
//   - userID: ID of the user uploading the order
//   - number: Unique order number
//
// Returns:
//   - error: ErrAlreadyExists if order exists, or database error
func (r *PostgresRepository) CreateOrder(ctx context.Context, userID int64, number string) error {
	const query = `
		INSERT INTO orders (number, user_id, status, uploaded_at)
		VALUES ($1, $2, $3, $4)
	`

	_, err := r.db.ExecContext(
		ctx,
		query,
		number,
		userID,
		model.OrderStatusNew,
		time.Now(),
	)
	if err != nil {
		var pgErr *pgconn.PgError
		if errors.As(err, &pgErr) && pgErr.Code == "23505" {
			return ErrAlreadyExists
		}

		return err
	}

	return nil
}

